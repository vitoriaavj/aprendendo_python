#OPERADORES RELACIONAIS OU COMPRAÇÃO

num1 = int(input("Digite um Número \n"))
num2 = int(input("Digite outro Número \n"))

print(f"{num1} é igual {num2}? {num1 == num2}")
print(f" {num1} é maior {num2}? {num1 > num2}")
print(f" {num1} é menor {num2}? {num1 < num2}")
print(f"{num1} é maior ou igual a {num2}? {num1 >= num2}")
print(f"{num1} é menor ou igual a {num2}? {num1 <= num2}")